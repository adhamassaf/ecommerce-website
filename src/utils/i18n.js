export const normalizeLocaleValue = (value, fallback = '') => {
  if (value == null) return { en: fallback, ar: fallback };

  if (typeof value === 'string') {
    return { en: value, ar: value };
  }

  if (typeof value === 'object') {
    return {
      en: value.en != null ? String(value.en) : fallback,
      ar:
        value.ar != null
          ? String(value.ar)
          : value.en != null
            ? String(value.en)
            : fallback,
    };
  }

  return { en: fallback, ar: fallback };
};

export const getLocalized = (value, language = 'en', fallback = '') => {
  const normalized = normalizeLocaleValue(value, fallback);
  const primary = normalized[language] || '';
  if (primary.trim()) return primary;
  return normalized.en || normalized.ar || fallback;
};

export const hasTranslation = (value, language) => {
  if (!value || typeof value !== 'object') return false;
  return Boolean(String(value[language] || '').trim());
};

